import { readdirSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

/** @typedef {'entry' | 'hashed' | 'public'} CacheClass */

/** @type {Record<CacheClass, string>} */
export const CACHE_CONTROL = Object.freeze({
  entry: 'no-cache',
  public: 'no-cache',
  hashed: 'public, max-age=31536000, immutable',
})

/**
 * @param {{ assetsDir: string, publicPathnames: ReadonlySet<string> }} config
 * @returns {ReadonlyArray<{ class: CacheClass, match: (pathname: string) => boolean }>}
 */
export function classRules(config) {
  const prefix = '/' + config.assetsDir.replace(/^\/|\/$/g, '') + '/'
  return Object.freeze([
    { class: 'hashed', match: (p) => p.startsWith(prefix) },
    { class: 'public', match: (p) => config.publicPathnames.has(p) },
    { class: 'entry', match: () => true },
  ])
}

/**
 * @param {string} pathname
 * @param {{ assetsDir: string, publicPathnames: ReadonlySet<string> }} config
 * @returns {CacheClass}
 */
export function classify(pathname, config) {
  const rule = classRules(config).find((row) => row.match(pathname))
  return rule.class
}

/**
 * @param {string} rawUrl
 * @param {{ assetsDir: string, publicPathnames: ReadonlySet<string> }} config
 * @returns {CacheClass}
 */
export function classifyRequestUrl(rawUrl, config) {
  const pathname = decodeURI(new URL(rawUrl, 'http://spa.local').pathname)
  return classify(pathname, config)
}

/**
 * @param {CacheClass} cacheClass
 * @returns {{ cacheControl: string }}
 */
export function headersFor(cacheClass) {
  return { cacheControl: CACHE_CONTROL[cacheClass] }
}

/**
 * @param {string} value
 * @returns {string}
 */
function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/**
 * @param {{ assetsDir: string, publicPathnames: ReadonlySet<string> }} config
 * @returns {string}
 */
export function emitNginxLocations(config) {
  const assetsDir = config.assetsDir.replace(/^\/|\/$/g, '')
  const publicNames = [...config.publicPathnames]
    .map((pathname) => pathname.replace(/^\//, ''))
    .filter(Boolean)
    .sort()
    .map(escapeRegex)

  const lines = [
    '# Generated by emitNginxLocations. Do not edit.',
    `location ^~ /${assetsDir}/ {`,
    `    add_header Cache-Control "${CACHE_CONTROL.hashed}";`,
    '    try_files $uri =404;',
    '}',
    '',
  ]

  if (publicNames.length > 0) {
    lines.push(
      `location ~ ^/(?:${publicNames.join('|')})$ {`,
      `    add_header Cache-Control "${CACHE_CONTROL.public}";`,
      '}',
      '',
    )
  }

  lines.push(
    'location / {',
    `    add_header Cache-Control "${CACHE_CONTROL.entry}";`,
    '    try_files $uri $uri/ /index.html;',
    '}',
    '',
  )

  return lines.join('\n')
}

/**
 * @param {string} publicDir
 * @returns {ReadonlySet<string>}
 */
export function listPublicPathnames(publicDir) {
  const pathnames = new Set()
  walkPublicFiles(publicDir, publicDir, pathnames)
  return pathnames
}

/**
 * @param {string} dir
 * @param {string} root
 * @param {Set<string>} pathnames
 */
function walkPublicFiles(dir, root, pathnames) {
  let entries
  try {
    entries = readdirSync(dir, { withFileTypes: true })
  } catch {
    return
  }

  for (const entry of entries) {
    const fullPath = join(dir, entry.name)
    if (entry.isDirectory()) {
      walkPublicFiles(fullPath, root, pathnames)
      continue
    }
    if (!entry.isFile()) {
      continue
    }
    const relativePath = relative(root, fullPath).split(sep).join('/')
    const pathname = '/' + relativePath
    if (pathname === '/index.html' || pathname.startsWith('/assets/')) {
      continue
    }
    pathnames.add(pathname)
  }
}
